export function describeSystemdTimer(unit: string, lang: string): string {
  const u = (unit || '').toLowerCase();
  for (const key of Object.keys(TIMER_DICT)) {
    if (key !== 'default' && u.includes(key)) {
      return TIMER_DICT[key][lang] || TIMER_DICT[key].en;
    }
  }
  return TIMER_DICT.default[lang] || TIMER_DICT.default.en;
}

export function describeCronSchedule(expr: string, lang: string): string {
  const e = (expr || '').trim();
  const s = getSecurityCronStrings(lang);
  const days = WEEK_DAYS_MAP[lang] || WEEK_DAYS_MAP.en;

  if (e === '@reboot') return s.modeReboot;
  if (e === '@hourly' || e === '0 * * * *') return `${s.everyLabel} 1 ${s.hoursUnit} (:00)`;
  if (e === '@daily' || e === '0 0 * * *') return `${s.modeDaily} 00:00`;
  if (e === '@weekly') return `${s.modeWeekly} (${days[0]} 00:00)`;
  if (e === '@monthly') return lang === 'fa' ? 'اول هر ماه ساعت ۰۰:۰۰' : 'Monthly (01 · 00:00)';

  const parts = e.split(/\s+/);
  if (parts.length !== 5) return e;
  const [min, hour, dom, mon, dow] = parts;

  if (min.startsWith('*/') && hour === '*' && dom === '*' && mon === '*' && dow === '*') {
    return `${s.everyLabel} ${min.slice(2)} ${s.minutesUnit}`;
  }
  if (/^\d+$/.test(min) && hour.startsWith('*/') && dom === '*' && mon === '*' && dow === '*') {
    return `${s.everyLabel} ${hour.slice(2)} ${s.hoursUnit} (:${min.padStart(2, '0')})`;
  }
  if (/^\d+$/.test(min) && /^\d+$/.test(hour) && dom === '*' && mon === '*' && dow === '*') {
    return `${s.modeDaily} ${hour.padStart(2, '0')}:${min.padStart(2, '0')}`;
  }
  if (/^\d+$/.test(min) && /^\d+$/.test(hour) && dom === '*' && mon === '*' && /^\d+$/.test(dow)) {
    const dIdx = parseInt(dow, 10) % 7;
    return `${s.modeWeekly} (${days[dIdx]}) ${hour.padStart(2, '0')}:${min.padStart(2, '0')}`;
  }
  return e;
}