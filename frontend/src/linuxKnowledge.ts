export function describeProcess(command: string, lang: string): string {
  const c = (command || '').toLowerCase();
  for (const [needle, key] of PROCESS_RULES) {
    if (c.includes(needle)) return pick(key, lang);
  }
  return '';
}

export function describeService(name: string, fallbackDesc: string, lang: string): string {
  const n = (name || '').toLowerCase();
  for (const [needle, key] of SERVICE_RULES) {
    if (n.includes(needle)) {
      const translated = pick(key, lang);
      if (translated) return translated;
    }
  }
  return fallbackDesc || '';
}

export function describeTerminalCommand(cmd: string, lang: string): string {
  const c = (cmd || '').toLowerCase().trim();
  for (const [needle, key] of TERMINAL_CMD_RULES) {
    if (c.includes(needle)) {
      const translated = pick(key, lang);
      if (translated) return translated;
    }
  }
  return cmd.trim();
}

